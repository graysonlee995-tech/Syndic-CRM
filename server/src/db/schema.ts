/** Every column holding a country. */
const COUNTRY_COLUMNS = [
  ['clients', 'nationality'],
  ['clients', 'country'],
  ['companies', 'country'],
  ['contact_addresses', 'country'],
  ['documents', 'issuing_country'],
] as const;

/** Brings rows from a backup made before migration 6 in line with it (see that migration). */
export function upgradeBackupRow(table: string, row: Record<string, unknown>, version: number): Record<string, unknown> {
  if (version < 10) {
    for (const [t, column] of COUNTRY_COLUMNS) {
      if (t === table && typeof row[column] === 'string') row = { ...row, [column]: canonicalCountry(row[column] as string) ?? row[column] };
    }
  }
  if (table === 'documents' && version < 9) {
    if (row.type === 'national_id') row = { ...row, type: 'residence_permit' };
    if (row.type === 'other' && !row.other_type) row = { ...row, other_type: 'Other document' };
  }
  if (table === 'open_credits' && version < 8 && !row.row_key) {
    row = { ...row, row_key: `restored-${row.trip_id}-${row.id}` };
  }
  if (version >= 6) return row;
  if (table === 'trips' && (row.status === 'planned' || row.status === 'confirmed')) return { ...row, status: 'active' };
  if (table === 'trip_itinerary') {
    if (row.type === 'hotel') return { ...row, name: row.origin ?? null, origin: null };
    if (row.type === 'cruise' || row.type === 'transfer' || row.type === 'other') {
      const prefix = row.type === 'cruise' ? 'Cruise' : row.type === 'transfer' ? 'Transfer' : '';
      const route = [row.origin, row.destination].filter(Boolean).join(' → ');
      return { ...row, type: 'other', name: [prefix, route].filter(Boolean).join(' ') || null, origin: null };
    }
  }
  return row;
}

/** Arbitrary constant identifying the migration lock. */
const MIGRATION_LOCK = 72_041_001;

export async function migrate(db: Runner & { transaction<T>(fn: (r: Runner) => Promise<T>): Promise<T> }): Promise<void> {
  // Several server instances can start at once (serverless). A transaction-level
  // lock makes them take turns; the later ones then find nothing left to do.
  // Everything commits together or not at all.
  await db.transaction(async (t) => {
    await t.query('SELECT pg_advisory_xact_lock($1)', [MIGRATION_LOCK]);
    await t.exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
      version integer PRIMARY KEY,
      applied_at timestamptz NOT NULL DEFAULT now()
    );
    ALTER TABLE schema_migrations ENABLE ROW LEVEL SECURITY;`);
    const { rows } = await t.query('SELECT COALESCE(MAX(version), 0) AS v FROM schema_migrations', []);
    for (let version = Number(rows[0].v); version < MIGRATIONS.length; version++) {
      const migration = MIGRATIONS[version];
      if (typeof migration === 'string') await t.exec(migration);
      else await migration(t);
      await t.query('INSERT INTO schema_migrations (version) VALUES ($1)', [version + 1]);
    }
  });
}
