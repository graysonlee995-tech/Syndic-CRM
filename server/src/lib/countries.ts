const key = (s: string) =>
  s
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9 ]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

const BY_KEY = new Map<string, string>();
for (const c of COUNTRIES) {
  BY_KEY.set(key(countryLabel(c)), countryLabel(c));
  BY_KEY.set(key(c.name), countryLabel(c));
  BY_KEY.set(key(c.code), countryLabel(c));
}
for (const [alias, code] of Object.entries(ALIASES)) {
  const c = COUNTRIES.find((x) => x.code === code)!;
  if (!BY_KEY.has(key(alias))) BY_KEY.set(key(alias), countryLabel(c));
}

/** The list's form of a country ("pakistan", "PK", "Pakistani", "UAE" -> "PK - Pakistan", "AE - United Arab Emirates"), or null if not on the list. */
export function canonicalCountry(value: string): string | null {
  return BY_KEY.get(key(value)) ?? null;
}
